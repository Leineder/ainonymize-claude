function vocabularyVerdict(surface, category, isGivenName) {
  const nfc = String(surface).normalize("NFC");
  const all = (nfc.match(TOKEN_RE) || []).filter((t) => t.length > 1);
  const words = new Set(nfc.match(/[\p{L}\p{M}]+/gu) || []);
  const isLowercaseContent = (t) => words.has(t) && t[0] !== t[0].toUpperCase() && !NAME_PARTICLES.has(t);
  if (!all.length) return "drop";
  if (all.some((t) => isGivenName(t))) return "keep";
  const informative = all.filter((t) => !isShortAcronym(t) && !TITLE_TOKEN_RE.test(t));
  const tokens = informative.length ? informative : all;
  if (category === "PERSON" && tokens.length >= 3 && tokens.filter(isLowercaseContent).length >= 2) return "drop";
  if (tokens.length === 1 && hasGermanSafeSuffix(tokens[0].toLowerCase())) return "drop";
  if (!tokens.every((t) => isCommonWord(t) || category === "PERSON" && isLowercaseContent(t))) return "keep";
  const hasFunction = tokens.some((t) => FUNCTION_WORDS.has(t.toLowerCase()));
  const content = tokens.filter((t) => !FUNCTION_WORDS.has(t.toLowerCase()));
  const n = content.length;
  if (n === 0) return "drop";
  if (n === 1) {
    const tok = content[0];
    const firstLower = tok[0].toLowerCase() === tok[0] && tok[0].toUpperCase() !== tok[0];
    if (firstLower || hasSafeSuffix(tok.toLowerCase())) return "drop";
    return category === "ORG" ? "drop" : "downgrade";
  }
  const allLower = content.every((t) => t[0].toLowerCase() === t[0] && t[0].toUpperCase() !== t[0]);
  if (hasFunction || n >= 3 || category === "ORG" || allLower) return "drop";
  return "downgrade";
}

