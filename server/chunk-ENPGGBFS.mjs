function isEnglishRoleWord(word) {
  const value = String(word || "").toLowerCase();
  return ENGLISH_ROLE_HEADS.has(value) || GERMAN_KINSHIP_AND_PARTY_WORDS.has(value) || /^(?:bond|share|stake|note|unit|policy|account|security|securities|copyright|licen[cs]e|sub|co)-?(?:holders?|owners?|processors?|controllers?)$/.test(value);
}
function hasEnglishRoleHead(surface) {
  const tokens = String(surface || "").trim().split(/\s+/).filter(Boolean);
  if (tokens.length < 2) return false;
  const last = tokens[tokens.length - 1].toLowerCase().replace(/[^a-z]/g, "");
  return !!last && isEnglishRoleWord(last);
}
